public class _20_AssignmentOP {
    public static void main(String args[]){
        int A = 10;
        //Assignment Operators
        //A = A + 10;
        A += 10; // Java executes this statement faster
        System.out.println(A);

        int B = 5;
        //B = B - 5;
        B -= 5; // Java executes this statement faster
        System.out.println(B);

        int C = 10;
        //C = C * 5;
        C *= 5; // Java executes this statement faster
        System.out.println(C);

        int D = 10;
        //D = D / 5;
        D /= 5; // Java executes this statement faster
        System.out.println(D);
        
        int E = 10;
        //E = E % 5;
        E %= 5; // Java executes this statement faster
        System.out.println(E);

    }
}